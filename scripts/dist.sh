#!/usr/bin/env bash
# Builds release archives for the common platforms into dist/ and writes SHA256SUMS.
# Nothing in the source tree is modified; the version is injected with -ldflags.
#
#   scripts/dist.sh                  # version from git (git describe)
#   VERSION=1.2.3 scripts/dist.sh
#
# Output per platform: assay_<version>_<os>_<arch>.tar.gz (.zip for Windows), containing the binary,
# LICENSE and README.md. With dpkg-deb available, .deb packages for linux/amd64 and linux/arm64 as well.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"
MODULE="github.com/SandSoftwareSolutions/assay"
VERSION="${VERSION:-$(git describe --tags --always --dirty 2>/dev/null | sed 's/^v//' || echo dev)}"
COMMIT="${COMMIT:-$(git rev-parse --short HEAD 2>/dev/null || echo none)}"
DATE="${DATE:-$(date -u +%Y-%m-%dT%H:%M:%SZ)}"
LDFLAGS="-s -w -X $MODULE/internal/cli.Version=$VERSION -X $MODULE/internal/cli.Commit=$COMMIT -X $MODULE/internal/cli.Date=$DATE"
OUT="$ROOT/dist"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
mkdir -p "$OUT"

TARGETS=(linux/amd64 linux/arm64 darwin/amd64 darwin/arm64 windows/amd64 windows/arm64)

for target in "${TARGETS[@]}"; do
  os="${target%/*}"; arch="${target#*/}"
  name="assay_${VERSION}_${os}_${arch}"
  dir="$WORK/$name"
  mkdir -p "$dir"
  bin="assay"; [ "$os" = windows ] && bin="assay.exe"
  echo "[build] $os/$arch"
  CGO_ENABLED=0 GOOS="$os" GOARCH="$arch" go build -trimpath -ldflags "$LDFLAGS" -o "$dir/$bin" .
  cp LICENSE README.md "$dir/"
  if [ "$os" = windows ]; then
    if command -v zip >/dev/null 2>&1; then
      (cd "$WORK" && zip -qr "$OUT/$name.zip" "$name")
    else
      python3 -c 'import shutil, sys; shutil.make_archive(sys.argv[1], "zip", sys.argv[2], sys.argv[3])' "$OUT/$name" "$WORK" "$name"
    fi
  else
    tar -C "$WORK" -czf "$OUT/$name.tar.gz" "$name"
  fi
done

if command -v dpkg-deb >/dev/null 2>&1; then
  for arch in amd64 arm64; do
    pkg="$WORK/deb-$arch"
    mkdir -p "$pkg/DEBIAN" "$pkg/usr/bin"
    cp "$WORK/assay_${VERSION}_linux_${arch}/assay" "$pkg/usr/bin/assay"
    chmod 755 "$pkg/usr/bin/assay"
    # Shell completions and the manual page, generated by the program itself. The amd64 binary is the one that can
    # run on the build machine; the text is the same for arm64.
    host="$WORK/assay_${VERSION}_linux_amd64/assay"
    if "$host" version >/dev/null 2>&1; then
      mkdir -p "$pkg/usr/share/bash-completion/completions" "$pkg/usr/share/zsh/vendor-completions" \
        "$pkg/usr/share/fish/vendor_completions.d" "$pkg/usr/share/man/man1"
      "$host" completion bash > "$pkg/usr/share/bash-completion/completions/assay"
      "$host" completion zsh > "$pkg/usr/share/zsh/vendor-completions/_assay"
      "$host" completion fish > "$pkg/usr/share/fish/vendor_completions.d/assay.fish"
      "$host" man | gzip -9n > "$pkg/usr/share/man/man1/assay.1.gz"
    else
      echo "[warn] cannot run the linux/amd64 binary here; the .deb gets no completions or manual page"
    fi
    cat > "$pkg/DEBIAN/control" <<CONTROL
Package: assay
Version: ${VERSION#v}
Section: devel
Priority: optional
Architecture: $arch
Maintainer: Sand Software Solutions <info@sandsoftwaresolutions.nl>
Description: See whether files were changed
 Assay records a hash of every file in a folder and later shows which files
 were modified, added, removed or renamed. Manifests can be signed.
CONTROL
    dpkg-deb --root-owner-group --build "$pkg" "$OUT/assay_${VERSION}_${arch}.deb" >/dev/null
    echo "[deb] assay_${VERSION}_${arch}.deb"
  done
else
  echo "[skip] dpkg-deb not found, no .deb packages"
fi

(cd "$OUT" && : > SHA256SUMS && for f in *.tar.gz *.zip *.deb; do [ -e "$f" ] && sha256sum "$f" >> SHA256SUMS; done; true)
echo "Done. Artifacts and SHA256SUMS are in $OUT"
