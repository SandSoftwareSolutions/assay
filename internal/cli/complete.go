package cli

import (
	"bytes"
	"context"
	"fmt"
	"io"
	"sort"
	"strings"
)

// commandInfo describes one command, for completion scripts and the man page. The flags are read from the
// commands themselves (their -h output), so these files can never list a flag that does not exist or miss one.
type commandInfo struct {
	Name       string
	Summary    string
	Positional string // what follows the command: "folder", "old.json new.json", ...
	Flags      []flagInfo
}

type flagInfo struct {
	Name  string // without dashes
	Usage string
	Arg   bool // takes a value
	File  bool // the value is a file name
}

// Long names are written with two dashes, single letters with one.
func (f flagInfo) Dashed() string {
	if len(f.Name) == 1 {
		return "-" + f.Name
	}
	return "--" + f.Name
}

var summaries = []struct{ name, summary, positional string }{
	{"seal", "record a hash of every file in a folder in a manifest", "[folder]"},
	{"check", "compare a folder with its manifest", "[folder]"},
	{"diff", "compare two manifests", "<old.json> <new.json>"},
	{"report", "write an HTML report of a check", "[folder]"},
	{"export", "print the manifest as sha256sum lines", "[folder]"},
	{"keygen", "create an Ed25519 key pair for signing", ""},
	{"completion", "print a completion script for a shell", "<bash|zsh|fish|powershell>"},
	{"man", "print the manual page", ""},
	{"version", "print the version", ""},
}

// commandInfos returns the commands with the flags each one accepts.
func (a *App) commandInfos() []commandInfo {
	var out []commandInfo
	for _, s := range summaries {
		ci := commandInfo{Name: s.name, Summary: s.summary, Positional: s.positional}
		switch s.name {
		case "seal", "check", "diff", "report", "export", "keygen":
			var buf bytes.Buffer
			(&App{Out: io.Discard, Err: &buf}).Run(context.Background(), []string{s.name, "-h"})
			ci.Flags = parseFlagHelp(buf.String())
		}
		out = append(out, ci)
	}
	return out
}

// parseFlagHelp reads the output of the standard flag package:
//
//	-algo string
//	  	hash algorithm: sha256, sha512 (default "sha256")
//	-q	print nothing but errors
func parseFlagHelp(text string) []flagInfo {
	var flags []flagInfo
	lines := strings.Split(text, "\n")
	for i := 0; i < len(lines); i++ {
		line := lines[i]
		if !strings.HasPrefix(line, "  -") {
			continue
		}
		head := strings.TrimPrefix(line, "  -")
		usage := ""
		if tab := strings.Index(head, "\t"); tab >= 0 { // bool flag: "q<TAB>usage"
			usage = strings.TrimSpace(head[tab+1:])
			head = head[:tab]
		}
		fields := strings.Fields(head)
		if len(fields) == 0 {
			continue
		}
		f := flagInfo{Name: fields[0], Arg: len(fields) > 1}
		if usage == "" && i+1 < len(lines) {
			usage = strings.TrimSpace(lines[i+1])
			i++
		}
		f.Usage = usage
		f.File = f.Arg && len(fields) > 1 && fields[1] == "file"
		if f.Name == "h" || f.Name == "help" {
			continue
		}
		flags = append(flags, f)
	}
	sort.SliceStable(flags, func(i, j int) bool { return flags[i].Name < flags[j].Name })
	return flags
}

func (a *App) completion(args []string) (int, error) {
	if len(args) != 1 {
		return ExitError, fmt.Errorf("usage: assay completion <bash|zsh|fish|powershell>")
	}
	infos := a.commandInfos()
	var script string
	switch args[0] {
	case "bash":
		script = bashCompletion(infos)
	case "zsh":
		script = zshCompletion(infos)
	case "fish":
		script = fishCompletion(infos)
	case "powershell":
		script = powershellCompletion(infos)
	default:
		return ExitError, fmt.Errorf("unknown shell %q (bash, zsh, fish or powershell)", args[0])
	}
	fmt.Fprint(a.Out, script)
	return ExitOK, nil
}

func names(infos []commandInfo) []string {
	out := make([]string, len(infos))
	for i, c := range infos {
		out[i] = c.Name
	}
	return out
}

func flagWords(c commandInfo) string {
	words := make([]string, len(c.Flags))
	for i, f := range c.Flags {
		words[i] = f.Dashed()
	}
	return strings.Join(words, " ")
}

func fileFlags(infos []commandInfo) []string {
	set := map[string]bool{}
	for _, c := range infos {
		for _, f := range c.Flags {
			if f.File {
				set[f.Dashed()] = true
			}
		}
	}
	out := make([]string, 0, len(set))
	for k := range set {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

func bashCompletion(infos []commandInfo) string {
	var b strings.Builder
	b.WriteString("# bash completion for assay (generated by \"assay completion bash\")\n_assay() {\n")
	b.WriteString("  local cur prev cmd flags\n  COMPREPLY=()\n  cur=\"${COMP_WORDS[COMP_CWORD]}\"\n  prev=\"${COMP_WORDS[COMP_CWORD-1]}\"\n  cmd=\"${COMP_WORDS[1]}\"\n")
	fmt.Fprintf(&b, "  if [ \"$COMP_CWORD\" -eq 1 ]; then\n    COMPREPLY=( $(compgen -W \"%s\" -- \"$cur\") )\n    return\n  fi\n", strings.Join(names(infos), " "))
	fmt.Fprintf(&b, "  case \"$prev\" in\n    %s)\n      COMPREPLY=( $(compgen -f -- \"$cur\") )\n      return ;;\n    --algo)\n      COMPREPLY=( $(compgen -W \"sha256 sha512\" -- \"$cur\") )\n      return ;;\n  esac\n", strings.Join(fileFlags(infos), "|"))
	b.WriteString("  case \"$cmd\" in\n")
	for _, c := range infos {
		switch c.Name {
		case "completion":
			b.WriteString("    completion) COMPREPLY=( $(compgen -W \"bash zsh fish powershell\" -- \"$cur\") ); return ;;\n")
		default:
			fmt.Fprintf(&b, "    %s) flags=\"%s\" ;;\n", c.Name, flagWords(c))
		}
	}
	b.WriteString("  esac\n  if [[ \"$cur\" == -* ]]; then\n    COMPREPLY=( $(compgen -W \"$flags\" -- \"$cur\") )\n  else\n    COMPREPLY=( $(compgen -d -- \"$cur\") )\n  fi\n}\ncomplete -o filenames -F _assay assay\n")
	return b.String()
}

func zshQuote(s string) string {
	s = strings.NewReplacer("[", "(", "]", ")", "'", "'\\''").Replace(s)
	return s
}

func zshCompletion(infos []commandInfo) string {
	var b strings.Builder
	b.WriteString("#compdef assay\n# zsh completion for assay (generated by \"assay completion zsh\")\n\n_assay() {\n  local -a commands\n  commands=(\n")
	for _, c := range infos {
		fmt.Fprintf(&b, "    '%s:%s'\n", c.Name, zshQuote(strings.ReplaceAll(c.Summary, ":", "\\:")))
	}
	b.WriteString("  )\n  if (( CURRENT == 2 )); then\n    _describe 'command' commands\n    return\n  fi\n  case $words[2] in\n")
	for _, c := range infos {
		switch c.Name {
		case "completion":
			b.WriteString("    completion) _values 'shell' bash zsh fish powershell ;;\n")
		case "diff":
			b.WriteString("    diff) _arguments '--json[print as JSON]' '*:manifest:_files -g \"*.json\"' ;;\n")
		case "version", "man":
			fmt.Fprintf(&b, "    %s) ;;\n", c.Name)
		default:
			fmt.Fprintf(&b, "    %s) _arguments \\\n", c.Name)
			for _, f := range c.Flags {
				switch {
				case f.File:
					fmt.Fprintf(&b, "      '%s[%s]:file:_files' \\\n", f.Dashed(), zshQuote(f.Usage))
				case f.Name == "algo":
					fmt.Fprintf(&b, "      '%s[%s]:algorithm:(sha256 sha512)' \\\n", f.Dashed(), zshQuote(f.Usage))
				case f.Arg:
					fmt.Fprintf(&b, "      '%s[%s]:value:' \\\n", f.Dashed(), zshQuote(f.Usage))
				default:
					fmt.Fprintf(&b, "      '%s[%s]' \\\n", f.Dashed(), zshQuote(f.Usage))
				}
			}
			b.WriteString("      '*:folder:_files -/' ;;\n")
		}
	}
	b.WriteString("  esac\n}\n\n_assay \"$@\"\n")
	return b.String()
}

func fishQuote(s string) string { return "'" + strings.ReplaceAll(s, "'", "\\'") + "'" }

func fishCompletion(infos []commandInfo) string {
	var b strings.Builder
	b.WriteString("# fish completion for assay (generated by \"assay completion fish\")\ncomplete -c assay -f\n")
	for _, c := range infos {
		fmt.Fprintf(&b, "complete -c assay -n '__fish_use_subcommand' -a %s -d %s\n", c.Name, fishQuote(c.Summary))
	}
	b.WriteString("complete -c assay -n '__fish_seen_subcommand_from completion' -a 'bash zsh fish powershell'\n")
	for _, c := range infos {
		for _, f := range c.Flags {
			opt := "-l " + f.Name
			if len(f.Name) == 1 {
				opt = "-s " + f.Name
			}
			arg := ""
			switch {
			case f.File:
				arg = " -r -F"
			case f.Name == "algo":
				arg = " -x -a 'sha256 sha512'"
			case f.Arg:
				arg = " -x"
			}
			fmt.Fprintf(&b, "complete -c assay -n '__fish_seen_subcommand_from %s' %s%s -d %s\n", c.Name, opt, arg, fishQuote(f.Usage))
		}
	}
	return b.String()
}

func powershellCompletion(infos []commandInfo) string {
	var b strings.Builder
	b.WriteString("# PowerShell completion for assay (generated by \"assay completion powershell\")\n")
	b.WriteString("$assayFlags = @{\n")
	for _, c := range infos {
		quoted := make([]string, len(c.Flags))
		for i, f := range c.Flags {
			quoted[i] = "'" + f.Dashed() + "'"
		}
		fmt.Fprintf(&b, "  '%s' = @(%s)\n", c.Name, strings.Join(quoted, ", "))
	}
	b.WriteString("}\nRegister-ArgumentCompleter -Native -CommandName assay -ScriptBlock {\n  param($wordToComplete, $commandAst, $cursorPosition)\n  $words = $commandAst.CommandElements | ForEach-Object { $_.ToString() }\n")
	b.WriteString("  if ($words.Count -le 1 -or ($words.Count -eq 2 -and $wordToComplete -ne '')) {\n    $assayFlags.Keys | Sort-Object | Where-Object { $_ -like \"$wordToComplete*\" } | ForEach-Object { [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_) }\n    return\n  }\n")
	b.WriteString("  $cmd = $words[1]\n  if ($cmd -eq 'completion') { 'bash','zsh','fish','powershell' | Where-Object { $_ -like \"$wordToComplete*\" } | ForEach-Object { [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_) }; return }\n")
	b.WriteString("  if ($assayFlags.ContainsKey($cmd)) {\n    $assayFlags[$cmd] | Where-Object { $_ -like \"$wordToComplete*\" } | ForEach-Object { [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterName', $_) }\n  }\n}\n")
	return b.String()
}

func (a *App) man() (int, error) {
	infos := a.commandInfos()
	esc := func(s string) string { return strings.NewReplacer(`\`, `\\`, "-", `\-`).Replace(s) }
	var b strings.Builder
	fmt.Fprintf(&b, ".TH ASSAY 1 \"\" \"assay %s\" \"User Commands\"\n", esc(Version))
	b.WriteString(".SH NAME\nassay \\- see whether files were changed\n")
	b.WriteString(".SH SYNOPSIS\n")
	for _, c := range infos {
		fmt.Fprintf(&b, ".B assay %s\n%s\n.br\n", c.Name, esc(c.Positional))
	}
	b.WriteString(".SH DESCRIPTION\n.B assay\nrecords a cryptographic hash of every file in a folder (a \\fImanifest\\fR) and later shows which files were modified, added, removed or renamed. A manifest can be signed with an Ed25519 key, so that replacing it after tampering with the files is noticed. A hash shows that a file changed, not who changed it.\n")
	b.WriteString(".SH COMMANDS\n")
	for _, c := range infos {
		fmt.Fprintf(&b, ".TP\n.B %s %s\n%s.\n", c.Name, esc(c.Positional), esc(c.Summary))
		for _, f := range c.Flags {
			arg := ""
			if f.Arg {
				arg = " \\fIvalue\\fR"
			}
			fmt.Fprintf(&b, ".RS\n.TP\n\\fB%s\\fR%s\n%s\n.RE\n", esc(f.Dashed()), arg, esc(f.Usage))
		}
	}
	b.WriteString(".SH EXIT STATUS\n.TP\n.B 0\nNothing changed (check), or the command succeeded.\n.TP\n.B 1\nDifferences were found, the manifest is damaged or a signature is invalid.\n.TP\n.B 2\nAn error: bad usage, unreadable files, no manifest.\n")
	b.WriteString(".SH FILES\n.TP\n.I .assay.json\nThe manifest, by default inside the sealed folder.\n.TP\n.I .assayignore\nPatterns (as in .gitignore) for files that are left out; the patterns in effect are stored in the manifest.\n")
	b.WriteString(".SH EXAMPLES\n.nf\nassay seal ./backups\nassay check ./backups --json\nassay keygen \\-o release\nassay seal ./dist \\-\\-key release.key\nassay check ./dist \\-\\-pubkey release.pub \\-\\-require\\-signature\n.fi\n")
	b.WriteString(".SH SEE ALSO\nhttps://github.com/SandSoftwareSolutions/assay\n.SH LICENSE\nGNU Affero General Public License v3.0 or later.\n")
	fmt.Fprint(a.Out, b.String())
	return ExitOK, nil
}
